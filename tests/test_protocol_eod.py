def hexs(data: bytes) -> str:
    return " ".join(f"{b:02X}" for b in data)


# --- gold vectors (panzer docs/design.md §2.9) ---

def test_request_bomb_dev_gold():
    frame = build_cmd_request_frame(DATA_BOMB_DEV, 20)
    assert hexs(frame) == "AA 55 06 20 02 14 00 12 59"


def test_request_qr_task_gold():
    # matches the 电赛 F4 protocol.md original vector AA 55 06 20 01 00 00 84 BE
    frame = build_cmd_request_frame(DATA_QR_TASK, 0)
    assert hexs(frame) == "AA 55 06 20 01 00 00 84 BE"


def test_cmd_stop_gold():
    assert hexs(build_cmd_stop_frame()) == "AA 55 03 23 F5 F1"


def test_cmd_ack_gold():
    frame = build_cmd_ack_frame(DATA_BOMB_DEV, 50, 6)
    assert hexs(frame) == "AA 55 06 21 02 32 06 A8 6B"


def test_data_stream_target_dev_gold():
    # seq=1, TARGET_DEV, ex=+1200, ey=-300, ring=9, flags=FOUND|READY(HIT)
    sub = build_device_sub_payload(1200, -300, 9, DEV_FLAG_FOUND | DEV_FLAG_READY)
    frame = build_data_stream_frame(1, DATA_TARGET_DEV, sub)
    assert hexs(frame) == "AA 55 0B 24 01 03 B0 04 D4 FE 09 05 BE 06"


def test_data_stream_qr_task_gold():
    # seq=5, QR_TASK "312": sub_payload = flags(01) + len(03) + "312" + 15 pad zeros
    sub = build_qr_task_sub_payload(True, "312")
    frame = build_data_stream_frame(5, DATA_QR_TASK, sub)
    expected = ("AA 55 19 24 05 01 01 03 33 31 32 00 00 00 00 00 00 00 00 "
                "00 00 00 00 00 00 00 6A AF")
    assert hexs(frame) == expected


# --- parse round-trips ---

def test_parse_frame_roundtrip_device():
    frame = build_device_stream_frame(7, DATA_BOMB_DEV, -4999, 5000, COLOR_RED,
                                      DEV_FLAG_FOUND | DEV_FLAG_MATCH)
    parsed = parse_frame(frame)
    assert parsed is not None and parsed.frame_type == 0x24
    assert parsed.payload[0] == 7 and parsed.payload[1] == DATA_BOMB_DEV
    dev = parse_device_sub_payload(parsed.payload[2:])
    assert dev == {"error_x": -4999, "error_y": 5000, "id": COLOR_RED,
                   "flags": DEV_FLAG_FOUND | DEV_FLAG_MATCH}


def test_parse_frame_roundtrip_zone():
    frame = build_zone_stream_frame(3, DATA_HOME_DEV, 4999, -4999,
                                    DEV_FLAG_FOUND | DEV_FLAG_READY)
    parsed = parse_frame(frame)
    assert parsed is not None
    zone = parse_zone_sub_payload(parsed.payload[2:])
    assert zone == {"error_x": 4999, "error_y": -4999,
                    "flags": DEV_FLAG_FOUND | DEV_FLAG_READY}


def test_parse_frame_rejects_corruption():
    frame = bytearray(build_device_stream_frame(1, DATA_TARGET_DEV, 10, 20, 8, DEV_FLAG_FOUND))
    frame[-1] ^= 0xFF   # flip a CRC byte
    assert parse_frame(bytes(frame)) is None


# --- no-target frame semantics (§2.4: bit0=0 -> error/id fields MUST be 0) ---

def test_no_target_frame_zeroes_fields():
    sub = build_device_sub_payload(1234, 5678, COLOR_RED, 0)   # flags without FOUND
    assert sub == b"\x00\x00\x00\x00\x00\x00"
    sub_zone = build_zone_sub_payload(1234, 5678, DEV_FLAG_MATCH)  # no FOUND bit
    assert sub_zone == b"\x00\x00\x00\x00\x02"


def test_qr_task_no_decode_is_zeroed():
    sub = build_qr_task_sub_payload(False, "312")
    assert sub == b"\x00" * 20
    parsed = parse_qr_task_sub_payload(sub)
    assert parsed == {"decoded": False, "code": ""}


def test_qr_task_roundtrip():
    sub = build_qr_task_sub_payload(True, "312")
    assert len(sub) == 20
    parsed = parse_qr_task_sub_payload(sub)
    assert parsed == {"decoded": True, "code": "312"}


def test_qr_task_long_code_truncated_to_18():
    sub = build_qr_task_sub_payload(True, "1" * 30)
    assert len(sub) == 20
    assert parse_qr_task_sub_payload(sub)["code"] == "1" * 18


# --- clamping ---

def test_clamp_error():
    assert clamp_error(6000) == 5000
    assert clamp_error(-6000) == -5000
    assert clamp_error(0) == 0
    assert clamp_error(-4999) == -4999


def test_crc16_matches_reference_implementation():
    """crc16_ccitt must equal the naive bit-wise reference from the spec."""
    def reference(data: bytes) -> int:
        crc = 0xFFFF
        for byte in data:
            crc ^= byte << 8
            for _ in range(8):
                crc = ((crc << 1) ^ 0x1021) & 0xFFFF if crc & 0x8000 else (crc << 1) & 0xFFFF
        return crc

    for data in (b"", b"\x20\x02\x14\x00", b"\x24\x01\x03\xb0\x04\xd4\xfe\x09\x05"):
        assert crc16_ccitt(data) == reference(data)


